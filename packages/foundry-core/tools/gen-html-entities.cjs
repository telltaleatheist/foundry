// gen-html-entities.cjs � writes src/engine/epub/html-entities.ts: every HTML named
// entity in the `entities` package's decode trie, each verified through its strict
// decoder. Run from packages/foundry-core:
//   node tools/gen-html-entities.cjs ../../app/node_modules/entities src/engine/epub/html-entities.ts
const fs = require('fs'); const path = require('path');
const [pkg, out] = process.argv.slice(2).map((arg) => path.resolve(arg));
const { htmlDecodeTree: tree, determineBranch, BinTrieFlags, decodeHTMLStrict } = require(path.join(pkg, 'lib/decode.js'));
const names = new Map();
const CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789;';
// Every name in the decoder's own trie, walked the way its decoder steps.
function walk(index, prefix) {
  const current = tree[index];
  const valueLength = (current & BinTrieFlags.VALUE_LENGTH) >> 14;
  const name = prefix.replace(/;$/, '');
  if (valueLength > 0 && name.length > 0) {
    const ref = `&${name};`;
    const text = decodeHTMLStrict(ref);
    if (text !== ref) names.set(name, text);
  }
  if (prefix.endsWith(';')) return;
  for (const ch of CHARS) {
    const next = determineBranch(tree, current, index + Math.max(1, valueLength), ch.charCodeAt(0));
    if (next >= 0) walk(next, prefix + ch);
  }
}
walk(0, '');
const version = require(path.join(pkg, 'package.json')).version;
const licence = fs.readFileSync(path.join(pkg, 'LICENSE'), 'utf8').trim().split('\n').map((l) => ` * ${l}`.trimEnd()).join('\n');
const body = [...names].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([k, t]) => `  ${JSON.stringify(k)}: ${JSON.stringify(t).replace(/[\u0080-￿]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'))},`).join('\n');
fs.writeFileSync(out, `/**
 * html-entities — the HTML named character references, name to text.
 *
 * GENERATED by tools/gen-html-entities.cjs, never edited: ${names.size} names,
 * every name in the \`entities\` package's (${version}) decode table, each
 * checked through its strict decoder. A table's markup is normalized with it
 * on its way into the book (strict-xhtml.ts), so a named reference becomes the
 * character a reader sees. A name not in here is not guessed at: its \`&\` is
 * escaped and it stays visible as written.
 *
 * Generated from the \`entities\` package, whose licence follows, and which
 * the engine bundle carries (esbuild keeps a comment marked as a licence):
 *
 * @license BSD-2-Clause
 *
${licence}
 */
export const HTML_ENTITIES: Readonly<Record<string, string>> = {
${body}
};
`);
console.log(`wrote ${names.size} names`);
